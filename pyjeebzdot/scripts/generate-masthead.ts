// Generates the footer masthead's ink: "MLS" set in Manufacturing Consent
// (scripts/fonts/manufacturing-consent.ttf, SIL Open Font License 1.1)
// converted to SVG outline paths so Footer.astro can trace it like pen
// work — the same trace→fill pattern MLSSignature draws the mls signature
// with. Run `npm run generate:masthead` to regenerate (committed output:
// src/lib/masthead.ts).

import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const TEXT = "MLS";
const GLYPH_SIZE = 1000; // lay the type at ~1000 em units for a roomy viewBox
const PEN = 12; // stroke width in glyph units (~1% of width — a fine nib)
const PAD = 20; // viewBox padding so the pen edge never clips

const ttf = readFileSync(
  new URL("./fonts/manufacturing-consent.ttf", import.meta.url),
);
const font = opentype.parse(
  ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength),
);

const lay = (x: number, y: number) =>
  font.getPath(TEXT, x, y, GLYPH_SIZE, {
    kerning: true,
    features: { liga: true },
  });

// Lay the text on its natural baseline (0, 0) — opentype v2's 2-decimal
// path stringifier emits NaNs for paths re-laid at a shifted origin, so
// the origin shift happens in the viewBox instead. PAD keeps the pen
// stroke (PEN) from clipping at the edges.
const ink = lay(0, 0);
const box = ink.getBoundingBox();
const pad = PEN / 2 + PAD;

if ((ink.toPathData(2).match(/NaN/g) || []).length > 0) {
  throw new Error("opentype emitted NaN path data — aborting");
}

const viewBox = [
  (box.x1 - pad).toFixed(2),
  (box.y1 - pad).toFixed(2),
  (box.x2 - box.x1 + pad * 2).toFixed(2),
  (box.y2 - box.y1 + pad * 2).toFixed(2),
].join(" ");

const d = ink.toPathData(2);

writeFileSync(
  new URL("../src/lib/masthead.ts", import.meta.url),
  `// GENERATED by scripts/generate-masthead.ts — "${TEXT}" in Manufacturing
// Consent (scripts/fonts/manufacturing-consent.ttf) as outline paths.
// Regenerate with \`npm run generate:masthead\` after changing TEXT there.

export const MARK_D = ${JSON.stringify(d)};

export const MARK_VB = "${viewBox}";
`,
);

console.log(
  `✅ src/lib/masthead.ts — viewBox ${viewBox}, ${d.length} chars of ink`,
);
